# Набор моделей для «Кубо»: робот, монета, блоки, платформы, постаменты. Метры, Z вверх, «лицо» смотрит в -Y.
import math, numpy as np
from mathutils import Matrix, Vector
from geo import cr, fil, lathe, sweep, circle, rrect, Group

def rot_to(axis, at=(0, 0, 0)): return np.array(Matrix.Translation(at) @ Vector((0, 0, 1)).rotation_difference(Vector(axis).normalized()).to_matrix().to_4x4())

def build():
    kit, glow = Group("Kit"), Group("Glow"); slot = [0]; kit.wmax = kit.hmax = 1.5; glow.wmax = glow.hmax = 3.0
    def begin(tag, dens=1.0, same=False):
        if not same: slot[0] += 1
        kit.begin(tag, (slot[0] * 4.0, 0, 0), dens); glow.begin(tag)
    def box(g, x, y, z, sx, sy, sz, bev, mat, n=2):                     # скруглённый брусок с центром (x, y) и низом z
        b = min(bev, sz * 0.45); k = 1 - 2 * b / max(sx, sy)
        g.grid(sweep([(x, y, z), (x, y, z + b), (x, y, z + sz - b), (x, y, z + sz)], [k, 1, 1, k], section=rrect(sy, sx, bev, n), up=(1, 0, 0)), mat)

    # ---------- робот Кубо ----------
    begin("kubo_body")
    kit.grid(sweep([(0, 0, z) for z in (0.33, 0.342, 0.365, 0.56, 0.755, 0.778, 0.79)], [0.84, 0.94, 1, 1, 1, 0.94, 0.84], section=rrect(0.44, 0.50, 0.075, 3), up=(1, 0, 0)), "paint_y")
    kit.grid(sweep([(0, -0.208, 0.60), (0, -0.226, 0.60), (0, -0.230, 0.60)], [1, 1, 0.96], section=rrect(0.41, 0.20, 0.05, 3), up=(0, 0, 1)), "steel")          # рамка визора
    kit.grid(sweep([(0, -0.222, 0.60), (0, -0.2345, 0.60), (0, -0.2365, 0.60)], [1, 1, 0.94], section=rrect(0.355, 0.148, 0.04, 3), up=(0, 0, 1)), "visor")
    for sx in (1, -1):
        kit.grid(sweep([(sx * x, 0, 0.575) for x in (0.243, 0.262, 0.286, 0.292)], [0.074, 0.078, 0.078, 0.062], 20), "steel")                                    # плечевые шарниры
        kit.grid(sweep([(sx * x, 0, 0.575) for x in (0.288, 0.300, 0.304)], [0.034, 0.034, 0.026], 12), "gold")
        glow.grid(lathe(fil([(0, 0, 0), (0.036, 0, 0.004), (0.036, 0.004, 0.004), (0, 0.006, 0)]), 20, rot_to((0, -1, 0), (sx * 0.088, -0.2362, 0.605))), "glow_eye")
    for i in range(3): kit.grid(sweep([(-0.10, -0.2215, 0.455 - i * 0.028), (0.10, -0.2215, 0.455 - i * 0.028)], 1, section=rrect(0.012, 0.012, 0.003, 1), up=(0, 0, 1)), "steel")  # решётка
    kit.grid(sweep([(0, y, 0.43) for y in (0.205, 0.235, 0.275, 0.300)], [0.062, 0.062, 0.078, 0.074], 20, caps=False), "steel")                                   # сопло
    kit.grid(lathe([(0.062, 0.004), (0.058, 0), (0, 0)], 20, rot_to((0, 1, 0), (0, 0.262, 0.43))), "visor")
    kit.grid(lathe(fil([(0.036, 0.788, 0), (0.036, 0.800, 0.004), (0.016, 0.822, 0.004), (0, 0.824, 0)]), 16, np.array(Matrix.Translation((0.13, 0.06, 0)))), "steel")  # основание антенны
    begin("kubo_ant", same=True)
    kit.grid(sweep([(0.13, 0.06, 0.815), (0.13, 0.06, 0.925)], 0.0065, 8), "steel")
    kit.grid(lathe(cr([(0, 0.917), (0.014, 0.925), (0.02, 0.940), (0.014, 0.955), (0, 0.962)], 4), 14, np.array(Matrix.Translation((0.13, 0.06, 0)))), "gold")
    glow.grid(lathe(cr([(0, 0.958), (0.012, 0.964), (0.016, 0.976), (0.011, 0.988), (0, 0.993)], 4), 12, np.array(Matrix.Translation((0.13, 0.06, 0)))), "glow_eye")
    for tag, sx in (("kubo_footL", 1), ("kubo_footR", -1)):
        begin(tag, same=True)
        kit.grid(sweep([(sx * 0.13, y, 0.052) for y in (-0.175, -0.165, -0.13, 0.06, 0.092, 0.10)], [0.72, 0.88, 1, 1, 0.9, 0.78], section=rrect(0.172, 0.104, 0.032, 3), up=(0, 0, 1)), "paint_y")
        kit.grid(sweep([(sx * 0.13, 0.0, z) for z in (0.09, 0.36)], 0.043, 14), "steel")
        kit.grid(sweep([(sx * 0.13, 0.0, z) for z in (0.098, 0.106, 0.124, 0.132)], [0.046, 0.058, 0.058, 0.046], 16, caps=False), "gold")
    glow.begin("kubo_jet"); glow.grid(lathe([(0, 0), (0.054, 0), (0.03, 0.05), (0, 0.11)], 14, rot_to((0, 1, 0), (0, 0.268, 0.43))), "glow_jet")

    # ---------- монета ----------
    begin("coin")
    cp = fil([(0, -0.016, 0), (0.085, -0.016, 0.004), (0.10, -0.024, 0.004), (0.13, -0.024, 0.004), (0.145, -0.016, 0.004), (0.20, -0.016, 0.004), (0.215, -0.03, 0.005), (0.262, -0.03, 0.006), (0.272, -0.022, 0.004), (0.272, -0.012, 0), (0.272, 0.012, 0),
              (0.272, 0.022, 0.004), (0.262, 0.03, 0.006), (0.215, 0.03, 0.005), (0.20, 0.016, 0.004), (0.145, 0.016, 0.004), (0.13, 0.024, 0.004), (0.10, 0.024, 0.004), (0.085, 0.016, 0.004), (0, 0.016, 0)], n=2)
    kit.grid(lathe(cp, 64, rot_to((0, -1, 0)), knurl=(32, 0.03, -0.0135, 0.0135)), "gold")

    # ---------- блоки ----------
    begin("brick", 0.45); box(kit, 0, 0, 0, 1, 1, 1, 0.05, "sand")
    begin("step", 0.45); box(kit, 0, 0, 0, 1, 1, 1, 0.05, "basalt")
    for z in (0.2, 0.72): kit.grid(sweep([(0, 0, z), (0, 0, z + 0.012), (0, 0, z + 0.07), (0, 0, z + 0.082)], [0.972, 1, 1, 0.972], section=rrect(1.03, 1.03, 0.055, 2), up=(1, 0, 0), caps=False), "iron")
    begin("qb", 0.45); box(kit, 0, 0, 0, 1.08, 1.08, 1.08, 0.06, "bronze")
    for ax in ((1, 0, 0), (-1, 0, 0), (0, 1, 0), (0, -1, 0)):
        c = (ax[0] * 0.54, ax[1] * 0.54, 0.54)
        kit.grid(lathe(fil([(0.24, 0, 0), (0.30, 0, 0.004), (0.31, 0.014, 0.006), (0.27, 0.022, 0.006), (0.235, 0.014, 0.004), (0.235, 0, 0)]), 40, rot_to(ax, c)), "gold")
        glow.grid(lathe([(0.232, 0.006), (0, 0.006)], 32, rot_to(ax, c)), "glow_coin")
    begin("chunk", 0.6); kit.grid(sweep([(0, 0, -0.1), (0, 0, -0.06), (0, 0, 0.06), (0, 0, 0.1)], [0.7, 1, 1, 0.75], section=rrect(0.24, 0.3, 0.06, 2), up=(1, 0, 0)), "sand")

    # ---------- ветхий деревянный настил (падающая платформа 2.2 x 2.2, верх на 0.5) ----------
    begin("fall", 0.36); rng = np.random.default_rng(5)
    for i in range(5):
        y = (i - 2) * 0.44; a, b = -1.1 + rng.uniform(0, 0.05), 1.1 - rng.uniform(0, 0.05); dz = rng.uniform(-0.008, 0)
        kit.grid(sweep([(a, y, 0.457 + dz), (b, y, 0.457 + dz)], 1, section=rrect(0.086, 0.415, 0.012, 1), up=(0, 1, 0)), "wood_x")
        for x in (-0.7, 0.7): kit.grid(lathe(fil([(0, 0.5 + dz, 0), (0.024, 0.5 + dz, 0), (0.024, 0.506 + dz, 0.004), (0.012, 0.512 + dz, 0.004), (0, 0.513 + dz, 0)]), 10, np.array(Matrix.Translation((x, y, 0)))), "iron")
    for x in (-0.7, 0.7): kit.grid(sweep([(x, -1.04, 0.35), (x, 1.04, 0.35)], 1, section=rrect(0.15, 0.13, 0.012, 1), up=(0, 0, 1)), "wood_y")

    # ---------- лифт (2 x 2, верх на 0.55) ----------
    begin("lift", 0.42)
    kit.grid(sweep([(0, 0, z) for z in (0.43, 0.445, 0.535, 0.55)], [0.975, 1, 1, 0.99], section=rrect(2.0, 2.0, 0.14, 3), up=(1, 0, 0)), "paint_b")
    kit.grid(sweep([(0, 0, z) for z in (0.452, 0.462, 0.508, 0.518)], [1.0, 1.012, 1.012, 1.0], section=rrect(2.0, 2.0, 0.14, 3), up=(1, 0, 0), caps=False), "gold")
    kit.grid(lathe(fil([(0, 0.0, 0), (0.09, 0.012, 0.02), (0.20, 0.10, 0.03), (0.30, 0.15, 0.01), (0.30, 0.185, 0.008), (0.36, 0.185, 0.008), (0.36, 0.245, 0.008), (0.30, 0.245, 0.008), (0.33, 0.30, 0.03), (0.52, 0.40, 0.03), (0.56, 0.432, 0)]), 40), "steel")
    glow.grid(lathe([(0.362, 0.196), (0.368, 0.215), (0.362, 0.234)], 40), "glow_lift")
    for sx in (1, -1):
        for sy in (1, -1): kit.grid(lathe(fil([(0, 0.34, 0), (0.07, 0.35, 0.01), (0.09, 0.40, 0.01), (0.09, 0.432, 0)]), 16, np.array(Matrix.Translation((sx * 0.78, sy * 0.78, 0)))), "steel")

    # ---------- постаменты под фонари ----------
    begin("ped_big", 0.5); kit.grid(lathe(fil([(0, 0, 0), (0.50, 0, 0.01), (0.50, 0.11, 0.015), (0.43, 0.15, 0.02), (0.40, 0.58, 0.02), (0.46, 0.64, 0.015), (0.46, 0.72, 0.012), (0, 0.72, 0)]), 8), "basalt")
    begin("ped_small", 0.6); kit.grid(lathe(fil([(0, 0, 0), (0.26, 0, 0.008), (0.26, 0.07, 0.01), (0.21, 0.10, 0.012), (0.20, 0.30, 0.012), (0.24, 0.34, 0.01), (0.24, 0.38, 0.008), (0, 0.38, 0)]), 8), "sand")
    return kit, glow
